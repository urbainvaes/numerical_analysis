"""Generate the CSL variants of trad-abbrv.csl used by template.typ.

- fullcite.csl: for \\fullcite, without edition, DOI, URL or citation number;
- number.csl: prints only the citation number, so that it can be colored.

Run from this directory after editing trad-abbrv.csl: python3 make_variants.py
"""

from pathlib import Path

here = Path(__file__).parent
base = (here / "trad-abbrv.csl").read_text()


def variant(suffix, title, comment, replacements):
    s = base
    s = s.replace("<id>trad-abbrv-lecture-notes</id>", f"<id>trad-abbrv-lecture-notes-{suffix}</id>")
    s = s.replace("<title>Trad abbrv (lecture notes)</title>", f"<title>Trad abbrv (lecture notes, {title})</title>")
    s = s.replace("<!-- Approximation", f"<!-- GENERATED by make_variants.py. {comment} Approximation")
    for old, new in replacements:
        assert old in s, old
        s = s.replace(old, new)  # all occurrences
    (here / f"{suffix}.csl").write_text(s)


variant(
    "fullcite",
    "full citations",
    "Variant used for \\fullcite: no edition, DOI or URL.",
    [
        ('            <text macro="edition"/>\n', ""),
        ('      <text macro="doi-url"/>\n', ""),
        ('      <text variable="citation-number" prefix="[" suffix="]"/>\n', ""),
        # Otherwise the author list is laid out as a separate label column
        (' second-field-align="flush"', ""),
        # The sentence in the notes provides the final period
        ('<group delimiter=". " suffix=".">', '<group delimiter=". ">'),
    ],
)

variant(
    "number",
    "bare citation numbers",
    "Variant that prints only the citation number, used to color it.",
    [
        (
            """    <layout prefix="[" suffix="]" delimiter=", ">
      <group delimiter=", ">
        <text variable="citation-number"/>
        <text variable="locator"/>
      </group>
    </layout>""",
            """    <layout delimiter=", ">
      <text variable="citation-number"/>
    </layout>""",
        ),
    ],
)
